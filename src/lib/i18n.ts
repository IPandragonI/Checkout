export const DEFAULT_LANG: Lang = "fr";
const dicts: Record<Lang, Dict> = { fr, en };

/**
 * Current dictionary. Uses the default language until hydrated so server
 * HTML and the first client render always match.
 */
export function useT(): Dict {
  const hydrated = useHydrated();
  const lang = useSettings((s) => s.lang);
  return dicts[hydrated ? lang : DEFAULT_LANG];
}

/** Non-hook access for event handlers and utilities. */
export function getT(): Dict {
  return dicts[useSettings.getState().lang] ?? dicts[DEFAULT_LANG];
}
