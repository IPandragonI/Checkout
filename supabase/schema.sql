-- Checkout: accounts schema. Run in the Supabase SQL editor (or any Postgres client).
-- Match history of signed-in users is synced here; guests never touch it.
-- Safe to re-run, and it migrates databases that still have the removed online-rooms tables.
-- Uses single-quoted function bodies (no $$) so clients that split on ";" cope.

-- ---------------------------------------------------------------------------
-- Cleanup: the online rooms feature was removed.
-- ---------------------------------------------------------------------------

drop table if exists public.visits cascade;
drop table if exists public.players cascade;
drop table if exists public.rooms cascade;
drop function if exists public.bump_room_version();

-- ---------------------------------------------------------------------------
-- Match history. Each row belongs to exactly one user.
-- ---------------------------------------------------------------------------

create table if not exists public.matches (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  -- Client-side id (a uuid generated by the app).
  id text not null check (char_length(id) <= 80),
  -- When the last visit was played (the finish time for completed matches).
  played_at timestamptz not null,
  config jsonb not null,
  players jsonb not null,
  visits jsonb not null,
  updated_at timestamptz not null default now(),
  primary key (user_id, id)
);

-- Added after the first release: match timing and the session a match belongs to.
alter table public.matches add column if not exists started_at timestamptz;
alter table public.matches add column if not exists active_ms int check (active_ms >= 0);
alter table public.matches add column if not exists session_id text check (char_length(session_id) <= 80);

-- Columns that only made sense for online rooms.
alter table public.matches drop column if exists mode;
alter table public.matches drop column if exists room_code;

create index if not exists matches_user_played_idx on public.matches (user_id, played_at desc);

alter table public.matches enable row level security;

drop policy if exists "own matches readable" on public.matches;
drop policy if exists "own matches insertable" on public.matches;
drop policy if exists "own matches updatable" on public.matches;
drop policy if exists "own matches deletable" on public.matches;
create policy "own matches readable" on public.matches for select to authenticated using (user_id = auth.uid());
create policy "own matches insertable" on public.matches for insert to authenticated with check (user_id = auth.uid());
create policy "own matches updatable" on public.matches for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "own matches deletable" on public.matches for delete to authenticated using (user_id = auth.uid());

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as 'begin new.updated_at = now(); return new; end;';

drop trigger if exists matches_touch on public.matches;
create trigger matches_touch before update on public.matches
  for each row execute function public.touch_updated_at();
